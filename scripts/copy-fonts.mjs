// Copies the SAP "72" font from node_modules into the renderer so it is
// available offline. Runs automatically after `npm install`.
//
// If no font files are found, an empty fonts.css is written and the app uses
// the theme's fallback fonts (Arial, Helvetica).

import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const searchRoots = [
  'node_modules/@sap-theming/theming-base-content',
  'node_modules/@ui5/webcomponents-theming',
].map((p) => path.join(root, p));
const fontDir = path.join(root, 'src/renderer/public/fonts');
const cssFile = path.join(root, 'src/renderer/generated/fonts.css');

const WANTED = {
  '72-Regular.woff2': { family: '72', weight: 400 },
  '72-Bold.woff2': { family: '72', weight: 700 },
  '72Mono-Regular.woff2': { family: '72Mono', weight: 400 },
  '72Mono-Bold.woff2': { family: '72Mono', weight: 700 },
};

async function* walk(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

const found = new Map();
for (const dir of searchRoots) {
  for await (const file of walk(dir)) {
    const name = path.basename(file);
    if (name in WANTED && !found.has(name)) found.set(name, file);
  }
}

await mkdir(fontDir, { recursive: true });
await mkdir(path.dirname(cssFile), { recursive: true });

const faces = [];
for (const [name, file] of found) {
  await copyFile(file, path.join(fontDir, name));
  const { family, weight } = WANTED[name];
  faces.push(
    `@font-face {\n  font-family: '${family}';\n  font-weight: ${weight};\n  font-style: normal;\n  font-display: swap;\n  src: url('/fonts/${name}') format('woff2');\n}`,
  );
}

await writeFile(cssFile, `/* Generated by scripts/copy-fonts.mjs */\n${faces.join('\n\n')}\n`, 'utf8');

if (found.size === 0) {
  console.warn('[copy-fonts] No "72" font files found. The app will use fallback fonts.');
} else {
  console.log(`[copy-fonts] Copied ${found.size} font files: ${[...found.keys()].join(', ')}`);
}
